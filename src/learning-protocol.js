export const LEARNING_PROTOCOL = `# 学习协议

## 一、什么在管辖范围内
- 本协议只管**任务型技能**：约束某类任务的做法、违反会当场变差的那类。
- **纪律型内容不进技能库** —— 它们必须每轮都在场，因此写在系统提示里；发现这类内容时应当建议写进系统提示，而不是建技能。
- **纪律层（系统提示）只有用户可要求修改。**

## 二、证据从哪来
1. **使用记录**（钩子自动记，不靠自觉）：哪个技能、什么 revision、哪个会话、什么时候被加载。
2. **用户信号**（钩子自动记）：用户消息。**它可能晚到** —— 在另一个对话、几天之后，甚至只是"复用旧结果时偶然发现问题"。判断留到事后。
3. **自评**（模型按提示写）：只在"感到困难/绕路/返工"时写。顺利不写 —— 强逼每次评价会让模型编造好评，反而污染数据。

## 三、归因靠桥，且只是候选
反馈带 (session, t)，使用记录带 (session, t)，记忆体里的产物带 (sessionId, createdAt)。
于是"**同会话、时间在反馈之前、最近的那次使用**"就是候选归因。
**这是推断，不是事实** —— 所以它带置信度，且下面的门槛会兜底。

## 四、证据强度 ↔ 改动幅度
- **强**（用户明说不满意）→ 可以增删规则点。
- **中强**（用户改了模型产出、复用旧结果时发现问题）→ 可以增删规则点，但必须在 why 里说明依据。
- **弱**（沉默、只有使用无反馈）→ **不驱动任何修改**，只维持。

## 五、六条「不改」（默认行为是"什么都不做"）
1. 无未消费记录 → 不改。
2. 只有使用、无负反馈 → 不改（沉默 ≠ 满意）。
3. 反馈的 revision ≠ 当前 revision → 不改（技能已改过，旧反馈不算新版头上）。
4. **归因不可证伪** → 不改：必须指出"改掉或新增哪一条规则会让这条反馈消失"；指不出具体规则点就记为观察项。
5. **缺反例** → 不改：说不出"改之前会做错、改之后应做对"的具体场景，就是没有证据。
6. **回归门不过** → 丢弃。

## 六、回归门
- **反例必需。**
- 正例优先用历史用例；冷启动期（还没有累积用例）退化为「**旧版规则点覆盖**」：
  新版必须逐条覆盖旧版规则点，措辞可改、**语义要点不能丢**。
  依据：冷启动期还没有累积下来的行为资产，"没丢"就等于"没弄坏"。
- **验证者与修订者必须是两次独立调用**，且验证者**拿不到修订理由**
  —— 给了理由它会偏向接受（自我一致性偏差）。

## 七、改动纪律
- **一次只改一个小点**；不要顺手重构。
- 通过后**直接迭代旧版**（不做分支），但写回前先把旧版全文存档（保证可回滚）。
- 全部改动留痕（含被拒绝的）。

## 八、生成门槛（新建技能）
新建技能**必须同时提供反例与正例**；做不了这两个验证，就不许生成。
另外：内容要用与技能提供者**同一套解析器**校验（能建出来就一定加载得起来）；
同名已存在时拒绝（改动已有技能应走评审，不是新建）。

## 九、本协议禁止自更新
它是学习系统的宪法，只能人工修改。任何自动流程都不得改写它。`
