/**
 * 注入文本的纯文本化。
 *
 * 为什么需要它（**这是同类缺陷第四次出现**）：
 *   本项目往「系统提示」和「工具结果」里注入的文本**不是 markdown 渲染的** ——
 *   `**加粗**` 会**原样显示成星号**，看起来像出错。
 *   四次踩坑记录：① 系统提示规则里混入 `**`；② `tool-guidance` 的引导文本；
 *   ③ tool-guidance 的测试断言补上了，但 ④ 新模块 `stuck-detector` 又忘了。
 *
 * 结论：**不要靠"记得加断言"，把它变成构造器出口的结构性约束** ——
 *   凡是要注入给模型的文本，一律先过这里。
 *
 * 注意：只去 markdown 的加粗/斜体星号，**保留反引号与中括号** ——
 *   在这两条通道里，反引号包围代码名是可读的约定，而星号只会像噪声。
 */
export function plain(text) {
  return String(text ?? '')
    .replace(/\*\*/g, '')   // 加粗
    .replace(/(^|\s)\*(?=\S)/g, '$1') // 行内斜体起始
    .replace(/(?<=\S)\*(\s|$)/g, '$1') // 行内斜体结束
}
